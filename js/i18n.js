// I18N ENGINE
// =====================================================
const I18n = {
    currentLang: 'vi', // Default: Vietnamese
    STORAGE_KEY: 'noithat_lang',

    init() {
        // Load saved language preference
        const saved = localStorage.getItem(this.STORAGE_KEY);
        if (saved && (saved === 'vi' || saved === 'en')) {
            this.currentLang = saved;
        }
        this.applyTranslations();
        this.updateToggleButtons();
        this.updateHtmlLang();
    },

    t(key) {
        const lang = translations[this.currentLang];
        return lang && lang[key] !== undefined ? lang[key] : (translations['vi'][key] || key);
    },

    switchLanguage(lang) {
        if (lang !== 'vi' && lang !== 'en') return;
        this.currentLang = lang;
        localStorage.setItem(this.STORAGE_KEY, lang);
        this.applyTranslations();
        this.updateToggleButtons();
        this.updateHtmlLang();
    },

    toggleLanguage() {
        this.switchLanguage(this.currentLang === 'vi' ? 'en' : 'vi');
    },

    applyTranslations() {
        // Apply text translations via data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (translation) {
                el.innerHTML = translation;
            }
        });

        // Apply placeholder translations via data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = this.t(key);
            if (translation) {
                el.setAttribute('placeholder', translation);
            }
        });

        // Apply title translations via data-i18n-title
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = this.t(key);
            if (translation) {
                el.setAttribute('title', translation);
            }
        });

        // Update page title
        const pageTitle = this.t('page.title');
        if (pageTitle) document.title = pageTitle;

        // Dispatch event for any custom handlers
        document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
    },

    updateToggleButtons() {
        const isVi = this.currentLang === 'vi';
        
        // Update all language toggle buttons
        document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
            const viLabel = btn.querySelector('.lang-seg-vi');
            const enLabel = btn.querySelector('.lang-seg-en');
            
            if (viLabel) viLabel.classList.toggle('active-seg', isVi);
            if (enLabel) enLabel.classList.toggle('active-seg', !isVi);
            
            btn.setAttribute('title', isVi ? 'Switch to English' : 'Chuyển sang Tiếng Việt');
            btn.setAttribute('aria-label', isVi ? 'Switch to English' : 'Chuyển sang Tiếng Việt');
        });
    },

    updateHtmlLang() {
        document.documentElement.setAttribute('lang', this.currentLang === 'vi' ? 'vi-VN' : 'en-US');
    }
};

// =====================================================
// LANGUAGE TOGGLE BUTTON CREATOR
// =====================================================
function createLangToggleButton(extraClasses = '') {
    const container = document.createElement('div');
    container.className = `lang-toggle-btn ${extraClasses}`.trim();
    container.innerHTML = `
        <button class="lang-seg lang-seg-vi" data-lang="vi" type="button" aria-label="Tiếng Việt">VI</button>
        <button class="lang-seg lang-seg-en" data-lang="en" type="button" aria-label="English">EN</button>
    `;
    
    // Add event listeners to segments
    container.querySelectorAll('.lang-seg').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.stopPropagation();
            const lang = btn.getAttribute('data-lang');
            I18n.switchLanguage(lang);
        });
    });
    
    return container;
}

