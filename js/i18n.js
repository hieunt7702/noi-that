// =====================================================
// AUTO-INJECT BUTTONS INTO THE PAGE
// =====================================================
function injectLangButtons() {
    // 1. Desktop header - inject next to theme switch button
    const headerSearchIcon = document.querySelector('.header-search-icon.hidden-xs.hidden-sm');
    if (headerSearchIcon && !headerSearchIcon.querySelector('.lang-toggle-btn')) {
        const langBtn = createLangToggleButton('header-lang-btn');
        langBtn.style.cssText = 'margin-right: 8px;';
        headerSearchIcon.insertBefore(langBtn, headerSearchIcon.firstChild);
    }

    // 2. Mobile menu - inject into mobile wrapper
    const mobileWrapper = document.querySelector('.mobile-wrapper.hidden-lg.hidden-md');
    if (mobileWrapper && !mobileWrapper.querySelector('.lang-toggle-btn')) {
        const langBtn = createLangToggleButton('header-lang-btn');
        langBtn.style.cssText = 'border-color: rgba(255,255,255,0.3); color: rgba(255,255,255,0.9);';
        mobileWrapper.insertBefore(langBtn, mobileWrapper.firstChild);
    }

    // 3. Fat-nav mobile menu overlay
    const fatNav = document.querySelector('.fat-nav__wrapper');
    if (fatNav && !fatNav.querySelector('.lang-toggle-btn')) {
        const langBtn = createLangToggleButton('mobile-lang-btn');
        fatNav.appendChild(langBtn);
    }
}

